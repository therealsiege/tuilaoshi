package journey

// Tribulation represents one of the 81 tribulations (八十一难) from Journey to the West.
type Tribulation struct {
	Number   int
	Name     string // Chinese name
	English  string // English name
	Desc     string // 1-sentence description of what happens at this trial
	Location string // place name in Chinese
}

// AllTribulations returns the complete list of 81 tribulations.
func AllTribulations() []Tribulation { return tribulations }

// TribulationAt returns the tribulation at the given number (1-81), or nil if not found.
func TribulationAt(n int) *Tribulation {
	for i := range tribulations {
		if tribulations[i].Number == n {
			return &tribulations[i]
		}
	}
	return nil
}

